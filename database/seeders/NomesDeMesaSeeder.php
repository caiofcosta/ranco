    public function run(): void
    {
        DB::transaction(function (): void {
            $agora = now();

            foreach (self::NOMES as $categoria => $nomes) {
                foreach ($nomes as $posicao => $nome) {
                    $existente = DB::table('opcoes')
                        ->where('lista', Lista::NomesDeMesa->value)
                        ->where('categoria', $categoria)
                        ->where('rotulo', $nome)
                        ->exists();

                    if ($existente) {
                        continue;
                    }

                    // A chave permanece igual mesmo quando o rótulo é editado no Painel.
                    DB::table('opcoes')->insertOrIgnore([
                        'lista' => Lista::NomesDeMesa->value,
                        'categoria' => $categoria,
                        'valor' => $categoria.'-'.Str::slug($nome),
                        'rotulo' => $nome,
                        'ordem' => 100 + $posicao,
                        'ativo' => true,
                        'created_at' => $agora,
                        'updated_at' => $agora,
                    ]);
                }
            }
        });
    }
